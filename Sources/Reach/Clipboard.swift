extension NSPasteboard.PasteboardType {
    /// 手边自己写进剪贴板的内容带这个标记，监听时跳过，不会重复进历史
    static let reachOwn = NSPasteboard.PasteboardType("me.ahuili.reach.own")
}

struct Payload {
    var plain: String = ""
    var html: String?
    var image: Data?
    var files: [URL] = []
    var containsSecret = false
}

enum Pasteboard {
    static func write(_ p: Payload) {
        let pb = NSPasteboard.general
        pb.clearContents()
        if !p.files.isEmpty {
            pb.writeObjects(p.files as [NSURL])
        } else if let img = p.image, let rep = NSImage(data: img) {
            pb.writeObjects([rep])
        } else {
            pb.setString(p.plain, forType: .string)
            if let h = p.html {
                let doc = "<meta charset=\"utf-8\"><div style=\"font-family:-apple-system,'PingFang SC',sans-serif;font-size:14px\">\(h)</div>"
                pb.setString(doc, forType: .html)
                if let d = doc.data(using: .utf8),
                   let attr = try? NSAttributedString(data: d, options: [.documentType: NSAttributedString.DocumentType.html,
                                                                         .characterEncoding: String.Encoding.utf8.rawValue], documentAttributes: nil),
                   let rtf = try? attr.data(from: NSRange(location: 0, length: attr.length), documentAttributes: [.documentType: NSAttributedString.DocumentType.rtf]) {
                    pb.setData(rtf, forType: .rtf)
                }
            }
        }
        pb.setString("1", forType: .reachOwn)
        if p.containsSecret {
            // 告诉其他剪贴板工具：这是敏感内容，别记
            pb.setString("", forType: NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType"))
        }
    }
}

enum Keys {
    static var trusted: Bool { AXIsProcessTrusted() }

    static func promptTrust() {
        let opts = [kAXTrustedCheckOptionPrompt.takeUnretainedValue() as String: true] as CFDictionary
        _ = AXIsProcessTrustedWithOptions(opts)
    }

    static func post(key: CGKeyCode, flags: CGEventFlags = []) {
        let src = CGEventSource(stateID: .combinedSessionState)
        for down in [true, false] {
            let e = CGEvent(keyboardEventSource: src, virtualKey: key, keyDown: down)
            e?.flags = flags
            e?.post(tap: .cghidEventTap)
        }
    }

    static func pasteKey() { post(key: 9, flags: .maskCommand) }   // ⌘V
    static func tabKey() { post(key: 48) }
}

// MARK: 监听复制

final class ClipboardMonitor {
    let model: AppModel
    var store: Store { model.store }
    private var timer: Timer?
    private(set) var lastCount = NSPasteboard.general.changeCount
    /// 最近一次真正由用户复制进来的那条
    private(set) var lastCapturedId: String? { didSet { lastCapturedCount = lastCount } }
    /// 记下那条时剪贴板的版本号。版本号变了说明剪贴板已经是别的内容
    private(set) var lastCapturedCount = -1
    var onCapture: (Item) -> Void = { _ in }

    init(model: AppModel) { self.model = model }

    func start() {
        timer = Timer.scheduledTimer(withTimeInterval: 0.4, repeats: true) { [weak self] _ in self?.tick() }
        RunLoop.main.add(timer!, forMode: .common)
    }

    /// 手边自己改了剪贴板后调用，免得被当成新内容
    func syncCount() { lastCount = NSPasteboard.general.changeCount }

    private func tick() {
        let pb = NSPasteboard.general
        guard pb.changeCount != lastCount else { return }
        lastCount = pb.changeCount
        guard !store.settings.paused else { return }
        let types = Set((pb.types ?? []).map(\.rawValue))
        if types.contains(NSPasteboard.PasteboardType.reachOwn.rawValue) { return }
        // 密码管理器等标记为"不要记录"的内容，尊重它
        if types.contains("org.nspasteboard.ConcealedType") || types.contains("org.nspasteboard.TransientType")
            || types.contains("org.nspasteboard.AutoGeneratedType") || types.contains("com.agilebits.onepassword") { return }
        let front = NSWorkspace.shared.frontmostApplication
        if front?.bundleIdentifier == Bundle.main.bundleIdentifier { return }
        guard var item = read(pb) else { return }
        item.sourceApp = front?.localizedName
        item.sourceBundle = front?.bundleIdentifier
        ingest(&item)
    }

    private func read(_ pb: NSPasteboard) -> Item? {
        if let urls = pb.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL], !urls.isEmpty {
            let paths = urls.map(\.path)
            return Item(kind: .clip, ctype: .file, text: paths.joined(separator: "\n"), files: paths,
                        hash: store.vault.fingerprint(Data(paths.joined(separator: "\n").utf8)))
        }
        if let s = pb.string(forType: .string), !s.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            guard s.utf8.count < 1_000_000 else { return nil }
            var it = Item(kind: .clip, text: s, hash: store.vault.fingerprint(Data(s.utf8)))
            if let h = pb.string(forType: .html), h.utf8.count < 300_000 { it.html = h }
            it.ctype = Classifier.classify(s)
            return it
        }
        if let d = pb.data(forType: .png) ?? pb.data(forType: .tiff), let rep = NSBitmapImageRep(data: d),
           let png = rep.representation(using: .png, properties: [:]), png.count < 20_000_000 {
            guard let file = store.saveImage(png) else { return nil }
            return Item(kind: .clip, ctype: .image, text: "", imageFile: file, hash: store.vault.fingerprint(png))
        }
        return nil
    }

    func ingest(_ item: inout Item) {
        let now = Date()
        // 和留存里某条一模一样：不重复记，只当作用了一次
        if let k = store.find(hash: item.hash, kind: .kept) { lastCapturedId = k.id; return }
        if var old = store.find(hash: item.hash, kind: .clip) {
            if let f = item.imageFile { try? FileManager.default.removeItem(at: ReachPaths.images.appendingPathComponent(f)) }
            old.createdAt = now
            old.sourceApp = item.sourceApp ?? old.sourceApp
            old.groupId = groupFor(now)
            old.expiresAt = expiry(old, now)
            store.save(old)
            lastCapturedId = old.id
            model.rebuild()
            onCapture(old)
            return
        }
        item.createdAt = now
        item.groupId = groupFor(now)
        // 整条就是密钥，或者一段文字里夹着密钥（连接串、带 Token 的命令）：都按敏感内容处理
        if item.ctype == .secret || (item.ctype != .image && item.ctype != .file && !SecretDetector.find(in: item.text).isEmpty) {
            item.sensitive = true
        }
        item.expiresAt = expiry(item, now)
        store.save(item)
        lastCapturedId = item.id
        model.rebuild()
        onCapture(item)
    }

    /// 整条是密钥的留 1 小时（可设置）；夹着密钥的留一天；其他按保留天数
    private func expiry(_ it: Item, _ now: Date) -> Date {
        if it.ctype == .secret { return now.addingTimeInterval(Double(store.settings.secretClipMinutes) * 60) }
        if it.sensitive { return now.addingTimeInterval(max(86400, Double(store.settings.secretClipMinutes) * 60)) }
        return now.addingTimeInterval(Double(store.settings.retentionDays) * 86400)
    }

    /// 自动成组：离上一条复制不到 10 分钟就算同一件事
    private func groupFor(_ now: Date) -> String {
        if let last = store.clips.first(where: { $0.origin != .agent }), now.timeIntervalSince(last.createdAt) < 600, let g = last.groupId { return g }
        return UUID().uuidString
    }
}

// MARK: 粘贴

enum PasteMode {
    case smart, plain, raw, cleanText, rich, codeOnly, jsonPretty, oneLine, ocr, login, shotPath
    case value(String, secret: Bool)
    case ai(String)
    case filled(String)
}

final class Paster {
    let model: AppModel
    weak var monitor: ClipboardMonitor?
    var store: Store { model.store }
    private var warnedTrust = false

    init(model: AppModel) { self.model = model }

    func options(for it: Item) -> [PasteOption] {
        var out: [PasteOption] = []
        let fs = model.fields(it)
        if it.ctype != .image && it.ctype != .file {
            out.append(PasteOption(label: "整条", detail: "↩", icon: "doc.plaintext", mode: .smart))
        }
        for f in fs {
            out.append(PasteOption(label: "只贴\(f.label)", icon: Self.fieldIcon(f.kind), detail: f.kind == .secret && !model.isRevealed(it) ? SecretDetector.maskValue(f.value) : Text.truncate(f.value, 44),
                                   mode: .value(f.value, secret: f.kind == .secret)))
        }
        if fs.contains(where: { $0.kind == .account }) && fs.contains(where: { $0.kind == .secret }) {
            out.append(PasteOption(label: "填登录框", detail: "账号 ⇥ 密码  ⌥↩", icon: "person.badge.key", mode: .login))
        }
        if it.ctype == .image {
            out.append(PasteOption(label: "图片", detail: "↩", icon: "photo", mode: .smart))
            out.append(PasteOption(label: "存成文件，贴路径", detail: "给终端里的 Agent", icon: "terminal", mode: .shotPath))
            if let o = it.ocr, !o.isEmpty { out.append(PasteOption(label: "图里的文字", detail: Text.firstLine(o, max: 30) ?? "", icon: "text.viewfinder", mode: .ocr)) }
            return out
        }
        if it.ctype == .file {
            out.append(PasteOption(label: "文件", detail: "↩", icon: "doc", mode: .raw))
            out.append(PasteOption(label: "路径", detail: "", icon: "folder", mode: .plain)); return out
        }
        out.append(PasteOption(label: "原样", detail: "保留复制时的格式", icon: "doc.richtext", mode: .raw))
        out.append(PasteOption(label: "纯文本", detail: "⇧↩", icon: "text.alignleft", mode: .plain))
        if Markdown.looksMarkdown(it.text) {
            out.append(PasteOption(label: "干净文字", detail: "去掉 ** ## 记号", icon: "eraser", mode: .cleanText))
            out.append(PasteOption(label: "带格式", detail: "标题、加粗、表格", icon: "bold", mode: .rich))
        }
        if !Markdown.codeBlocks(it.text).isEmpty { out.append(PasteOption(label: "只贴代码块", detail: "", icon: "chevron.left.forwardslash.chevron.right", mode: .codeOnly)) }
        if it.ctype == .json { out.append(PasteOption(label: "JSON 排整齐", detail: "", icon: "curlybraces", mode: .jsonPretty)) }
        if it.text.contains("\n") { out.append(PasteOption(label: "合成一行", detail: "", icon: "arrow.right.to.line", mode: .oneLine)) }
        if store.settings.ai.isReady, it.text.count > 8, !it.sensitive {
            out.append(PasteOption(label: "翻成英文", detail: "AI", icon: "globe", mode: .ai("把下面的内容翻译成自然的英文，只输出译文。")))
            out.append(PasteOption(label: "翻成中文", detail: "AI", icon: "globe.asia.australia", mode: .ai("把下面的内容翻译成自然的简体中文，只输出译文。")))
            out.append(PasteOption(label: "精简", detail: "AI", icon: "text.redaction", mode: .ai("把下面的内容精简到原来的一半以内，保留关键信息和数字，只输出结果。")))
        }
        return out
    }

    static func fieldIcon(_ k: FieldKind) -> String {
        switch k { case .url: return "link"; case .account: return "person"; case .secret: return "key"; case .host: return "server.rack"; case .command: return "terminal" }
    }

    /// 按目标窗口决定贴什么
    func payload(_ it: Item, mode: PasteMode, target: TargetKind) -> Payload? {
        var p = Payload()
        if it.ctype == .image {
            if case .ocr = mode { p.plain = it.ocr ?? ""; return p }
            // 贴进终端（Claude Code、Codex 这类命令行 Agent）：终端贴不了图，存成一个文件，贴它的路径，Agent 能直接读
            if case .shotPath = mode, let path = shotFile(it) { p.plain = path; return p }
            if target == .terminal, case .smart = mode, let path = shotFile(it) { p.plain = path; return p }
            guard let f = it.imageFile, let d = store.loadImage(f) else { return nil }
            p.image = d; return p
        }
        if it.ctype == .file {
            if case .plain = mode { p.plain = it.text; return p }
            p.files = (it.files ?? []).map { URL(fileURLWithPath: $0) }.filter { FileManager.default.fileExists(atPath: $0.path) }
            if p.files.isEmpty { p.plain = it.text }
            return p
        }
        let md = Markdown.looksMarkdown(it.text)
        let secrets = SecretDetector.find(in: it.text, loose: it.kind == .kept, ignoring: it.notSecret)
        switch mode {
        case .smart:
            // 回车贴整条（按目标窗口调整格式）。只贴密码、账号这些单项，按 → 选，或 ⌥↩ 一次填好登录框
            switch target {
            case .chat: p.plain = md ? Markdown.toPlain(it.text) : it.text
            case .rich:
                p.plain = it.text
                p.html = md ? Markdown.toHTML(it.text) : it.html
            case .terminal:
                p.plain = Markdown.forTerminal(it.text)
            default:
                p.plain = it.text
                p.html = it.html
            }
        case .plain: p.plain = it.text
        case .raw: p.plain = it.text; p.html = it.html
        case .cleanText: p.plain = Markdown.toPlain(it.text)
        case .rich: p.plain = it.text; p.html = Markdown.toHTML(it.text)
        case .codeOnly: p.plain = Markdown.codeBlocks(it.text).joined(separator: "\n\n")
        case .jsonPretty:
            if let d = it.text.data(using: .utf8), let o = try? JSONSerialization.jsonObject(with: d),
               let out = try? JSONSerialization.data(withJSONObject: o, options: [.prettyPrinted, .sortedKeys, .withoutEscapingSlashes]) {
                p.plain = String(data: out, encoding: .utf8) ?? it.text
            } else { p.plain = it.text }
        case .oneLine:
            p.plain = it.text.split(whereSeparator: \.isNewline).map { $0.trimmingCharacters(in: .whitespaces) }.filter { !$0.isEmpty }.joined(separator: " ")
        case .value(let v, let secret): p.plain = v; p.containsSecret = secret; return p
        case .filled(let t): p.plain = t
        case .ocr: p.plain = it.ocr ?? ""
        case .login, .ai, .shotPath: return nil
        }
        p.containsSecret = !secrets.isEmpty && secrets.contains { p.plain.contains($0.value) }
        return p
    }

    /// 截图存成临时 PNG（只有你自己能读，一天后清掉），返回路径
    func shotFile(_ it: Item) -> String? {
        guard let f = it.imageFile, let d = store.loadImage(f) else { return nil }
        let dir = FileManager.default.urls(for: .cachesDirectory, in: .userDomainMask)[0].appendingPathComponent("Reach/shots", isDirectory: true)
        try? FileManager.default.createDirectory(at: dir, withIntermediateDirectories: true, attributes: [.posixPermissions: 0o700])
        if let old = try? FileManager.default.contentsOfDirectory(at: dir, includingPropertiesForKeys: [.contentModificationDateKey]) {
            for u in old where ((try? u.resourceValues(forKeys: [.contentModificationDateKey]).contentModificationDate) ?? Date()) < Date().addingTimeInterval(-86400) {
                try? FileManager.default.removeItem(at: u)
            }
        }
        let url = dir.appendingPathComponent("截图-\(it.id.prefix(8)).png")
        guard (try? d.write(to: url, options: .atomic)) != nil else { return nil }
        try? FileManager.default.setAttributes([.posixPermissions: 0o600], ofItemAtPath: url.path)
        return url.path
    }

    func paste(_ it: Item, mode: PasteMode) {
        let target = TargetKind.of(bundle: model.targetBundle)
        if case .login = mode { login(it); return }
        if case .ai(let instruction) = mode { aiPaste(it, instruction: instruction); return }
        guard let p = payload(it, mode: mode, target: target) else { model.toast("这条贴不了"); return }
        // 密钥要贴进聊天窗口或 AI 对话框：先拦一下
        if p.containsSecret, target == .chat || target == .ai {
            if let c = model.confirmSecret, c.id == it.id, c.until > Date() {
                model.confirmSecret = nil
            } else {
                model.askSecretConfirm(it.id)
                return
            }
        }
        deliver(p, item: it)
    }

    func deliver(_ p: Payload, item: Item?) {
        Pasteboard.write(p)
        monitor?.syncCount()
        if let it = item { store.recordUse(it.id, app: model.targetBundle) }
        model.hidePanel()
        finishPaste(secret: p.containsSecret)
    }

    private func finishPaste(secret: Bool) {
        if Keys.trusted {
            DispatchQueue.main.asyncAfter(deadline: .now() + 0.08) { Keys.pasteKey() }
        } else {
            model.toast("已复制，按 ⌘V 粘贴。想让它自动贴：系统设置 › 隐私与安全性 › 辅助功能 里允许「手边」")
            if !warnedTrust { warnedTrust = true; Keys.promptTrust() }
        }
        if secret {
            // 密钥在剪贴板里只留 30 秒
            let count = NSPasteboard.general.changeCount
            DispatchQueue.main.asyncAfter(deadline: .now() + 30) { [weak self] in
                if NSPasteboard.general.changeCount == count { NSPasteboard.general.clearContents(); self?.monitor?.syncCount() }
            }
        }
    }

    /// 账号 → Tab → 密码，一次填完
    private func login(_ it: Item) {
        let fs = model.fields(it)
        guard let acc = fs.first(where: { $0.kind == .account }), let sec = fs.first(where: { $0.kind == .secret }) else { return }
        guard Keys.trusted else {
            model.toast("填登录需要先在 系统设置 › 隐私与安全性 › 辅助功能 里允许「手边」")
            Keys.promptTrust(); return
        }
        let target = TargetKind.of(bundle: model.targetBundle)
        if target == .chat || target == .ai {
            if let c = model.confirmSecret, c.id == it.id, c.until > Date() { model.confirmSecret = nil }
            else { model.askSecretConfirm(it.id); return }
        }
        store.recordUse(it.id, app: model.targetBundle)
        model.hidePanel()
        Pasteboard.write(Payload(plain: acc.value)); monitor?.syncCount()
        DispatchQueue.main.asyncAfter(deadline: .now() + 0.10) { Keys.pasteKey() }
        DispatchQueue.main.asyncAfter(deadline: .now() + 0.30) { Keys.tabKey() }
        DispatchQueue.main.asyncAfter(deadline: .now() + 0.45) { [weak self] in
            Pasteboard.write(Payload(plain: sec.value, containsSecret: true)); self?.monitor?.syncCount()
        }
        DispatchQueue.main.asyncAfter(deadline: .now() + 0.55) { Keys.pasteKey() }
        DispatchQueue.main.asyncAfter(deadline: .now() + 30) { [weak self] in
            if NSPasteboard.general.string(forType: .string) == sec.value { NSPasteboard.general.clearContents(); self?.monitor?.syncCount() }
        }
    }

    private func aiPaste(_ it: Item, instruction: String) {
        model.busy = "AI 处理中…"
        let text = SecretDetector.redact(it.text)
        let cfg = store.settings.ai
        Task { @MainActor in
            defer { self.model.busy = nil }
            do {
                let out = try await AIClient(cfg).complete(system: instruction, user: text, maxTokens: 1500)
                self.deliver(Payload(plain: out), item: it)
            } catch {
                self.model.toast("AI 没处理成：\(error)")
            }
        }
    }

    /// 把篮子里的几条合成一段贴出去
    func pasteBasket() {
        let target = TargetKind.of(bundle: model.targetBundle)
        let text = model.basketText(imagePaths: target == .terminal)
        guard !text.isEmpty else { return }
        if target == .chat || target == .ai, model.basket.compactMap({ store.items[$0] }).contains(where: { $0.sensitive || $0.ctype == .secret }) {
            model.toast("篮子里有密钥，没有贴进「\(model.targetName)」。把那条移出篮子再贴。")
            return
        }
        for id in model.basket { store.recordUse(id, app: model.targetBundle) }
        model.basket = []
        deliver(Payload(plain: text), item: nil)
    }
}

// MARK: 普通 ⌘V 也按目标窗口调整格式

final class Ambient {
    let model: AppModel
    let monitor: ClipboardMonitor
    private var modifiedFor: String?
    private var ownCount = -1
    private var warnedFor: String?
    private var obs: NSObjectProtocol?

    init(model: AppModel, monitor: ClipboardMonitor) {
        self.model = model; self.monitor = monitor
        obs = NSWorkspace.shared.notificationCenter.addObserver(forName: NSWorkspace.didActivateApplicationNotification, object: nil, queue: .main) { [weak self] n in
            guard let app = n.userInfo?[NSWorkspace.applicationUserInfoKey] as? NSRunningApplication else { return }
            self?.activated(app)
        }
    }

    private func activated(_ app: NSRunningApplication) {
        guard app.bundleIdentifier != Bundle.main.bundleIdentifier, app.bundleIdentifier != "com.apple.loginwindow" else { return }
        model.targetBundle = app.bundleIdentifier
        model.targetName = app.localizedName ?? ""
        let store = model.store
        let pb = NSPasteboard.general
        // 剪贴板里必须还是手边最后记下的那条（或者手边自己改过的版本），否则不动
        guard pb.changeCount == monitor.lastCapturedCount || pb.changeCount == ownCount,
              let id = monitor.lastCapturedId, let it = store.items[id], it.ctype != .image, it.ctype != .file else { return }
        let kind = TargetKind.of(bundle: app.bundleIdentifier)
        if it.sensitive || it.ctype == .secret, kind == .chat || kind == .ai {
            // 同一条只提醒一次
            if warnedFor != id {
                warnedFor = id
                model.toast("剪贴板里有密钥，当前窗口是「\(app.localizedName ?? "聊天窗口")」，贴之前留意一下")
            }
            return
        }
        guard store.settings.ambientFormat else { return }
        let md = Markdown.looksMarkdown(it.text)
        var p: Payload?
        switch kind {
        case .chat where md: p = Payload(plain: Markdown.toPlain(it.text))
        case .rich where md: p = Payload(plain: it.text, html: Markdown.toHTML(it.text))
        case .terminal where it.ctype == .command || it.text.hasPrefix("$ "):
            let t = Markdown.forTerminal(it.text)
            if t != it.text { p = Payload(plain: t) }
        default: break
        }
        if let p {
            guard modifiedFor != kind.rawValue + id else { return }
            Pasteboard.write(p)
            modifiedFor = kind.rawValue + id
        } else if modifiedFor != nil {
            // 换到别的窗口：把原样放回去
            Pasteboard.write(Payload(plain: it.text, html: it.html))
            modifiedFor = nil
        } else { return }
        ownCount = pb.changeCount
        monitor.syncCount()
    }
}
